def default_output_path(csv_path: Path) -> Path:
    """Derive the HTML output path next to the source CSV.

    Args:
        csv_path: Path to the source CSV file.

    Returns:
        Sibling path with an ``.html`` extension.
    """
    return csv_path.with_suffix(".html")


def parse_args(argv: Optional[List[str]]) -> argparse.Namespace:
    """Parse command-line arguments.

    Args:
        argv: Argument list (without the program name), or ``None`` to use
            ``sys.argv[1:]``.

    Returns:
        Parsed arguments namespace with ``input`` and ``output`` keys.
    """
    parser = argparse.ArgumentParser(
        description="Convert a JETRAG RAG evaluation experiment CSV into an HTML report.",
    )
    parser.add_argument(
        "-i", "--input",
        help="Path to the experiment CSV. Defaults to the newest file in experiments/.",
    )
    parser.add_argument(
        "-o", "--output",
        help="Path for the generated HTML. Defaults to the CSV path with a .html suffix.",
    )
    return parser.parse_args(argv)


def main(argv: Optional[List[str]] = None) -> int:
    """Entry point: load a CSV, render the HTML report, and write it to disk.

    Args:
        argv: Argument list for testing, defaults to ``sys.argv[1:]``.

    Returns:
        Process exit code (0 on success, 1 on handled errors).
    """
    raise_csv_field_size_limit()
    args = parse_args(argv)

    try:
        csv_path = resolve_input_csv(args.input)
        fieldnames, rows = load_rows(csv_path)
    except (FileNotFoundError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    specs = build_column_specs(fieldnames)
    summary = summarize(rows)
    document = render_html(csv_path.name, specs, rows, summary)

    output_path = Path(args.output).expanduser().resolve() if args.output else default_output_path(csv_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(document, encoding="utf-8")

    print(f"Read {summary['total']} row(s) from {csv_path}")
    print(f"Passed {summary['passed']} / Failed {summary['failed']} (pass rate {summary['pass_rate']:.1f}%)")
    print(f"HTML report written to: {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
